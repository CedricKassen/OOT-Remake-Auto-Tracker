#!/usr/bin/env python3
"""Generates lib/src/catalog.g.dart from tool/catalog.json (+ tool/names_extra.json).

catalog.json is the field catalog embedded in OOT-SW2SE's editor.html
(MIT, (c) 2026 Traiver and contributors). names_extra.json holds field names
found by this project: a JSON list of names; their hashes are computed here.
"""
import json, os
here = os.path.dirname(os.path.abspath(__file__))
cat = json.load(open(os.path.join(here, 'catalog.json')))

def murmur3(data: bytes) -> int:
    h = 0; n = len(data) & ~3
    for i in range(0, n, 4):
        k = int.from_bytes(data[i:i+4], 'little')
        k = (k * 0xcc9e2d51) & 0xffffffff; k = ((k << 15) | (k >> 17)) & 0xffffffff
        k = (k * 0x1b873593) & 0xffffffff
        h ^= k; h = ((h << 13) | (h >> 19)) & 0xffffffff; h = (h * 5 + 0xe6546b64) & 0xffffffff
    k = 0; t = data[n:]
    if len(t) >= 3: k ^= t[2] << 16
    if len(t) >= 2: k ^= t[1] << 8
    if len(t) >= 1:
        k ^= t[0]; k = (k * 0xcc9e2d51) & 0xffffffff; k = ((k << 15) | (k >> 17)) & 0xffffffff
        k = (k * 0x1b873593) & 0xffffffff; h ^= k
    h ^= len(data); h ^= h >> 16; h = (h * 0x85ebca6b) & 0xffffffff
    h ^= h >> 13; h = (h * 0xc2b2ae35) & 0xffffffff; h ^= h >> 16
    return h

known = {f[0] for f in cat['fields']}
names = {}   # hash -> real game name (hash verified)
labels = {}  # hash -> editor-made label (name does not hash to it)
for f in cat['fields']:
    if len(f) > 2:
        (names if murmur3(f[2].encode()) == f[0] else labels)[f[0]] = f[2]
extra_path = os.path.join(here, 'names_extra.json')
extra = json.load(open(extra_path)) if os.path.exists(extra_path) else []
skipped = []
for n in extra:
    h = murmur3(n.encode())
    if h in known: names[h] = n
    else: skipped.append(n)
def q(s): return "'" + s.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$') + "'"
out = ['// GENERATED by tool/gen_catalog.py - do not edit.',
       '// Field names from OOT-SW2SE (MIT, (c) 2026 Traiver and contributors) and this project.',
       '', '/// Field hash -> game field name (the hash is murmur3 of the name).',
       'const Map<int, String> fieldNames = {']
out += [f'  0x{h:08X}: {q(n)},' for h, n in sorted(names.items(), key=lambda x: x[1])]
out += ['};', '', '/// Field hash -> descriptive label for fields whose real name is unknown.',
        'const Map<int, String> fieldLabels = {']
out += [f'  0x{h:08X}: {q(n)},' for h, n in sorted(labels.items(), key=lambda x: x[1])]
out += ['};', '', '/// Inventory items: actor name, category, title, stock field hash.',
        'const List<(String, String, String, int)> inventoryItems = [']
out += [f'  ({q(a)}, {q(c)}, {q(t)}, 0x{h:08X}),' for h, a, c, _, t in cat['inventory']]
out += ['];', '']
open(os.path.join(here, '..', 'lib', 'src', 'catalog.g.dart'), 'w').write('\n'.join(out))
print(f'{len(names)} names, {len(labels)} labels, {len(cat["inventory"])} items; extra names not in save: {skipped}')
